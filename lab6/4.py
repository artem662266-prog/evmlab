class Solution:
    def canFinish(self, numCourses: int, prerequisites: List[List[int]]) -> bool:
        # Шаг 1: Строим граф в виде списка смежности
        # Ключ — курс, значение — список курсов, для которых он является требованием
        graph = {i: [] for i in range(numCourses)}
        for course, prereq in prerequisites:
            graph[prereq].append(course)
            
        # Список состояний для каждого курса: 0 - не начат, 1 - в процессе, 2 - завершен
        state = [0] * numCourses
        
        # Наша рекурсивная функция поиска цикла
        def has_cycle(v):
            # Если узел "серый" (1), значит мы вернулись туда, откуда начали — это ЦИКЛ!
            if state[v] == 1:
                return True
            # Если узел "черный" (2), он уже проверен и безопасен, заново смотреть не нужно
            if state[v] == 2:
                return False
                
            # Красим узел в "серый" (1) — начинаем проверку его зависимостей
            state[v] = 1
            
            # Проверяем все курсы, которые открываются после текущего
            for neighbor in graph[v]:
                if has_cycle(neighbor):
                    return True # Если дальше по цепочке нашелся цикл, передаем True наверх
                    
            # Если проверили всех соседей и цикла нет, красим узел в "черный" (2)
            state[v] = 2
            return False

        # Шаг 2: Запускаем проверку для каждого курса
        # Граф может быть несвязным (несколько независимых цепочек), поэтому проверяем все вершины
        for i in range(numCourses):
            if state[i] == 0: # Если курс еще не проверяли
                if has_cycle(i):
                    return False # Наткнулись на цикл — расписание составить нельзя
                    
        # Если обошли весь граф и ни одного цикла не нашли — всё отлично!
        return True

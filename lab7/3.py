class Solution:
    def lengthOfLIS(self, nums: List[int]) -> int:
        if not nums:
            return 0
            
        # Создаем массив dp размера n и заполняем единицами.
        # Каждый элемент сам по себе является возрастающей подпоследовательностью длины 1.
        dp = [1] * len(nums)
        
        # Внешний цикл: двигаем указатель i слева направо по всему массиву
        for i in range(len(nums)):
            # Внутренний цикл: перебираем все элементы j, которые стоят строго ДО элемента i
            for j in range(i):
                # Если элемент слева меньше текущего, мы можем продолжить возрастающую цепочку
                if nums[j] < nums[i]:
                    # Обновляем dp[i], выбирая максимум между тем, что там уже лежало,
                    # и длиной цепочки у элемента j плюс единица (сам элемент i)
                    dp[i] = max(dp[i], 1 + dp[j])
                    
        # Ответ — это самый большой рекорд, который нам удалось зафиксировать в массиве dp
        return max(dp)

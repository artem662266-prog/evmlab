class Solution:
    def rob(self, nums: List[int]) -> int:
        # Если на улице нет домов, грабить нечего
        if not nums:
            return 0
        # Если дом всего один, забираем из него всё
        if len(nums) == 1:
            return nums[0]
            
        # rob1 — это максимальный куш, который мы могли собрать два дома назад
        rob1 = 0
        # rob2 — это максимальный куш, который мы могли собрать в предыдущем доме
        rob2 = 0
        
        # Проходим по каждому дому на улице
        for current_house_money in nums:
            # Считаем, что выгоднее:
            # Вариант А: ограбить текущий дом (+ то, что наворовали через один дом назад: rob1)
            # Вариант Б: пропустить текущий дом (остаемся с кушем предыдущего дома: rob2)
            current_max = max(current_house_money + rob1, rob2)
            
            # Сдвигаем наши переменные вперед для следующего дома
            # То, что было в предыдущем доме (rob2), теперь становится историей "два дома назад"
            rob1 = rob2
            # Наш новый текущий рекорд становится "предыдущим домом" для следующего шага
            rob2 = current_max
            
        # В самом конце в rob2 окажется максимальная сумма для всей улицы
        return rob2

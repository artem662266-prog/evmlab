class Solution:
    def coinChange(self, coins: List[int], amount: int) -> int:
        # Создаем массив dp, где индекс — это промежуточная сумма от 0 до amount.
        # Заполняем его заведомо большим числом (amount + 1), которое играет роль бесконечности.
        dp = [amount + 1] * (amount + 1)
        
        # Базовый случай: для суммы 0 нужно ровно 0 монет
        dp[0] = 0
        
        # Перебираем все промежуточные суммы от 1 до нужного amount
        for i in range(1, amount + 1):
            # Для каждой суммы пробуем применить каждую из доступных монет
            for coin in coins:
                # Если номинал монеты не превышает текущую сумму, мы можем её взять
                if i - coin >= 0:
                    # Выбираем минимум: либо оставить старое решение для этой суммы,
                    # либо взять текущую монету (+1 монета) и посмотреть на остаток суммы: dp[i - coin]
                    dp[i] = min(dp[i], 1 + dp[i - coin])
        
        # Если в финальной ячейке осталась "бесконечность", значит сумму собрать нельзя
        if dp[amount] > amount:
            return -1
        else:
            return dp[amount]

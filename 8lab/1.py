class Solution:
    def subsets(self, nums: List[int]) -> List[List[int]]:
        result = []         # Список, куда мы сложим все найденные подмножества
        current_subset = [] # Наш рабочий буфер (текущее подмножество)
        
        # Рекурсивная функция бэктрекинга
        # i — индекс элемента в nums, решение по которому мы сейчас принимаем
        def backtrack(i):
            # Базовый случай: если индекс дошел до конца массива,
            # значит мы приняли решение по каждому числу. Пора фиксировать результат.
            if i >= len(nums):
                # Важно: добавляем КОПИЮ списка current_subset (через [:]),
                # иначе при изменении буфера изменятся и элементы в result
                result.append(current_subset[:])
                return
                
            # --- ВАРИАНТ 1: Мы решаем ВКЛЮЧИТЬ nums[i] в подмножество ---
            current_subset.append(nums[i])
            backtrack(i + 1) # Идем дальше к следующему числу
            
            # --- БЭКТРЕКИНГ (ШАГ НАЗАД) ---
            # Очищаем буфер, вытряхивая последний добавленный элемент,
            # чтобы подготовить его ко второму варианту
            current_subset.pop()
            
            # --- ВАРИАНТ 2: Мы решаем НЕ ВКЛЮЧАТЬ nums[i] в подмножество ---
            backtrack(i + 1) # Идем дальше к следующему числу без него

        # Запускаем бэктрекинг с самого первого элемента (индекс 0)
        backtrack(0)
        return result
